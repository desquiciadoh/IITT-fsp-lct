"""Family catalogue and topic × grade-band coverage (ML-6):  python -m assessment.families.catalog

Writes docs/ml/item-bank.md from the registry and the content files, so the table can't drift
from the code (tests/ml checks that the committed file is current). Pure: no Django.
"""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

from ..engine.cat import item_level
from ..engine.content import load_content
from .base import GRADES, ITEM_FORMATS, SPECS
from .registry import all_families

OUT = Path(__file__).resolve().parents[3] / "docs" / "ml" / "item-bank.md"
SPEC_RU = {"backend": "Backend", "frontend": "Frontend", "ml_data": "ML & Data"}


def render() -> str:
    content = load_content()
    fams = all_families()
    lines = [
        "# Item bank: families and coverage",
        "",
        "Generated by `python -m assessment.families.catalog` (from `apps/`); do not edit by hand.",
        "Grade band of a family = the band its difficulty prior `b` falls into (cuts −1 / 0 / +1, D7).",
        "Every family passes `python -m assessment.families.verify --n 1000` (oracle, one correct answer,",
        "collisions ≤ 0.1 %, answer entropy > 1 bit, option-only guessing ≤ c + max(0.05, 4 SE)).",
        "",
        "## Families per specialization",
        "",
        "| Specialization | Families | Formats used |",
        "|---|---|---|",
    ]
    for spec in SPECS:
        metas = [f.meta for f in fams.values() if spec in f.meta.specs]
        formats = sorted({m.format for m in metas}, key=ITEM_FORMATS.index)
        lines.append(f"| {SPEC_RU[spec]} | {len(metas)} | {', '.join(formats)} |")
    for spec in SPECS:
        lines += ["", f"## {SPEC_RU[spec]}: topic × grade band", "",
                  "| Topic | Weight | " + " | ".join(GRADES) + " | Total |",
                  "|---|---|" + "---|" * (len(GRADES) + 1)]
        metas = [f.meta for f in fams.values() if spec in f.meta.specs]
        for topic in content.topics_for(spec):
            bands = Counter(item_level(m) for m in metas if m.topic == topic)
            row = [content.topics[topic].name_ru, f"{content.blueprints[spec][topic]:.2f}"]
            row += [str(bands.get(g, 0)) or "0" for g in GRADES] + [str(sum(bands.values()))]
            lines.append("| " + " | ".join(row) + " |")
        totals = Counter(item_level(m) for m in metas)
        lines.append("| **Total** | 1.00 | " + " | ".join(str(totals.get(g, 0)) for g in GRADES)
                     + f" | {len(metas)} |")
    lines += ["", "## Catalogue", "", "| Family | Specs | Topic | Format | a | b | Level | c | Time, s |",
              "|---|---|---|---|---|---|---|---|---|"]
    for fid, fam in fams.items():
        m = fam.meta
        lines.append(f"| `{fid}` | {', '.join(m.specs)} | {m.topic} | {m.format} | {m.a:g} | {m.b:g} | "
                     f"{item_level(m)} | {m.c:.3g} | {m.time_limit_s} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(), encoding="utf-8")
    sys.stdout.write(f"wrote {OUT}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
